// One-time: creates the Ed25519 release signing key. The private key stays on this PC
// (%USERPROFILE%\.notetoo-release\, never in the repo); the public key is written into
// updater/releaseKey.mts, so every updater build trusts only releases signed with it.
// Usage: node scripts/release/keygen.mjs
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { KEY_FILE, PUBLIC_KEY_MODULE } from './paths.mjs';

if (existsSync(KEY_FILE)) {
  console.error(`A release key already exists at ${KEY_FILE}.\nReplacing it would make every installed updater refuse new releases. Nothing was changed.`);
  process.exit(1);
}
const { publicKey, privateKey } = generateKeyPairSync('ed25519');
mkdirSync(path.dirname(KEY_FILE), { recursive: true });
writeFileSync(KEY_FILE, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600, flag: 'wx' });
const pem = publicKey.export({ type: 'spki', format: 'pem' }).toString().trim();
writeFileSync(
  PUBLIC_KEY_MODULE,
  `// Generated by scripts/release/keygen.mjs. The updater only trusts releases signed with the matching private key.\nexport const RELEASE_PUBLIC_KEY = \`${pem}\n\`;\n`,
);
console.log(`Private key: ${KEY_FILE} (back it up somewhere safe; keep it secret)`);
console.log(`Public key:  ${path.relative(process.cwd(), PUBLIC_KEY_MODULE)}`);
